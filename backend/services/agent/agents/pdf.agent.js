import { getModel } from "../config/llmModels.js";

export const pdfAgent = async (state) => {
    try {
        const llm = await getModel("pdf");

        const prompt = `You are the DIU Academic Document & PDF Specialist.
Your task is to generate a formal, well-structured academic document or report based on the user's request.

Guidelines:
- Create professional university-grade content suitable for Daffodil International University (DIU) reports, assignments, lecture notes, or study summaries.
- Include structured sections:
  # Document Title
  ## Executive Summary / Overview
  ## Key Concepts & Details
  ## Methodologies / Analysis
  ## References & DIU Course Guidelines
- Provide markdown tables where appropriate.
- Maintain academic rigor and clarity.

User Request:
${state.prompt}`;

        const response = await llm.invoke(prompt);
        const docContent = response.content || "";

        const title = state.prompt.slice(0, 40) + (state.prompt.length > 40 ? "..." : "");

        return {
            ...state,
            aiResponse: docContent,
            artifacts: [
                {
                    id: Date.now(),
                    type: "Document",
                    title: `Document: ${title}`,
                    files: [
                        {
                            name: "document.md",
                            content: docContent
                        },
                        {
                            name: "index.html",
                            content: `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>${title}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; line-height: 1.6; max-width: 800px; margin: 40px auto; padding: 20px; color: #1e293b; }
    h1 { color: #1e3a8a; border-bottom: 2px solid #3b82f6; padding-bottom: 8px; }
    h2 { color: #1e40af; margin-top: 24px; }
    table { width: 100%; border-collapse: collapse; margin: 20px 0; }
    th, td { border: 1px solid #cbd5e1; padding: 10px; text-align: left; }
    th { background: #f1f5f9; }
    code { background: #f1f5f9; padding: 2px 6px; border-radius: 4px; font-family: monospace; }
  </style>
</head>
<body>
  <h1>${title}</h1>
  <p><em>Generated by DIU Copilot Academic Document Generator</em></p>
  <hr/>
  <div style="white-space: pre-wrap;">${docContent.replace(/</g, "&lt;").replace(/>/g, "&gt;")}</div>
</body>
</html>`
                        }
                    ]
                }
            ]
        };
    } catch (error) {
        console.error("Error from pdfAgent:", error);
        return {
            ...state,
            aiResponse: "I encountered an issue generating your academic document. Please try again.",
            artifacts: []
        };
    }
};
